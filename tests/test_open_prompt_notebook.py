# ---------------------------------------------------------------- execution


def _run(*overrides):
    environment = dict(os.environ)
    environment.pop("PYTHONPATH", None)
    environment["MMPILOT_REPO_DIR"] = str(REPO_ROOT)
    return subprocess.run(
        [sys.executable, str(RUNNER), str(NOTEBOOK_PATH), *overrides],
        cwd=REPO_ROOT.parent,
        env=environment,
        capture_output=True,
        text=True,
        timeout=900,
    )


@pytest.fixture(scope="module")
def executed():
    result = _run()
    assert result.returncode == 0, f"{result.stdout}\n{result.stderr}"
    return json.loads(result.stdout.strip().splitlines()[-1])


def test_the_notebook_runs_end_to_end_on_cpu(executed):
    assert executed["ok"] is True
    assert executed["run_real_open_prompt_study"] is False
    assert executed["mode"] == "mock"
    assert executed["status"] == "MOCK_PASSED"
    assert executed["loaded_gemma"] is False
    assert executed["torch_cuda_initialized"] is False


def test_the_legacy_prompt_is_reproduced_byte_for_byte(executed):
    legacy = executed["summary"]["legacy"]
    assert legacy["byte_for_byte_with_capability_module"] is True
    assert legacy["capability_protocol_string"] == "gemma-it-chat-balanced-options-v1"
    assert legacy["candidates_in_prompt"] is True
    assert legacy["maximum_claim"] == "candidate_conditioned_identification"


def test_the_open_prompts_name_no_candidate_in_any_modality(executed):
    section = executed["summary"]["open_identification"]
    assert section["question"] == (
        "What animal is present in the evidence? Answer with the animal name.\nAnswer:"
    )
    for modality, prompt in section["visible_prompt_by_modality"].items():
        for candidate in ("bird", "cat"):
            if modality == "text" and candidate == "bird":
                continue  # the caption legitimately says it; recorded below
            assert candidate not in prompt.lower(), (modality, candidate)
    assert section["candidates_are_external"] == {
        "text": True, "image": True, "spoken_audio": True
    }
    # The source is permitted and recorded in written evidence, and only there.
    assert section["source_in_visible_evidence"] == {
        "text": True, "image": False, "spoken_audio": False
    }
    # The target is nowhere: not in a prompt, not in the offline transcript.
    assert section["target_detected_anywhere"] == {
        "text": False, "image": False, "spoken_audio": False
    }


def test_every_refusal_fired(executed):
    assert set(executed["summary"]["refusals"]) == {
        "candidate_enumeration_in_the_open_question",
        "hidden_intermediate_source_in_transcript",
        "hidden_intermediate_source_in_visible_text",
        "hidden_intermediate_target_in_transcript",
        "property_answer_in_prompt",
        "semantic_filename_exposure",
        "target_in_audio_transcript",
        "target_in_visible_evidence",
        "unauditable_missing_transcript",
    }
    assert "source_in_visible_evidence" in executed["summary"]["protocol_separation"]


def test_the_transcript_never_crossed_into_the_backend(executed):
    assert executed["summary"]["transcript_reached_backend"] is False


def test_candidates_are_scored_externally_and_completely(executed):
    scoring = executed["summary"]["external_scoring"]
    assert scoring["all_multi_token"] is True
    assert scoring["order_invariance_max_abs_delta"] < 1e-9
    assert scoring["prompt_order_invariant"] is True


def test_order_leaves_the_fingerprint_alone_and_the_set_does_not(executed):
    assert executed["summary"]["fingerprint_sensitivity"] == {
        "order_changes_digest": False,
        "set_changes_digest": True,
        "set_changes_prompt_hash": False,
    }
    assert "not admissible for the primary" in executed["summary"][
        "primary_protocol_refusal"
    ]


def test_candidate_completion_positions_were_not_patched(executed):
    assert executed["summary"]["candidate_tail_bit_identical"] is True


def test_the_mock_effects_are_labelled_synthetic_and_support_no_claim(executed):
    summary = executed["summary"]
    assert summary["mock_effects"] == {
        "identity_clean": "bird",
        "identity_swapped": "cat",
        "property_clean": "two",
        "property_swapped": "four",
    }
    assert "synthetic plumbing only" in summary["mock_effects_are"]
    assert summary["ran_real_experiment"] is False
    assert all(admissible is False for admissible in summary["mock_claims_admissible"].values())


def test_the_notebook_is_deterministic():
    first, second = _run(), _run()
    assert first.returncode == 0 and second.returncode == 0
    a = json.loads(first.stdout.strip().splitlines()[-1])["summary"]
    b = json.loads(second.stdout.strip().splitlines()[-1])["summary"]
    assert a == b


def test_flipping_the_switch_refuses_instead_of_running_anything():
    result = _run("RUN_REAL_OPEN_PROMPT_STUDY=True")
    assert result.returncode == 1
    payload = json.loads(result.stdout.strip().splitlines()[-1])
    assert payload["ok"] is False
    assert "NotImplementedError" in payload["error"]
    assert "does not exist yet" in payload["error"]


# ------------------------------------------------------------ the schematic

SCHEMATIC_SVG = REPO_ROOT / "docs" / "assets" / "intervention_methods.svg"
SCHEMATIC_PNG = REPO_ROOT / "docs" / "assets" / "intervention_methods.png"


def test_the_schematic_draws_how_the_model_is_asked():
    svg = SCHEMATIC_SVG.read_text(encoding="utf-8")
    assert SCHEMATIC_PNG.read_bytes()[:8] == b"\x89PNG\r\n\x1a\n"

    # The completed side: the prompt it actually used, and the claim it carries.
    for statement in (
        "COMPLETED — candidate-listed identification",
        "mmpilot.candidate_listed_identification.v1",
        "bird, cat, giraffe, microwave, toilet, zebra?",
        "every candidate concept is inside the model's own input",
        "not disclose which candidate is correct",
        "Supports: candidate-conditioned cross-modal causal steering.",
        "Does not establish spontaneous, unprompted concept emergence",
        "may prime their J-space representations",
    ):
        assert statement in svg, statement

    # The planned side: the open prompts, and the boundary the scorer sits on.
    for statement in (
        "PLANNED — open prompt, candidates external to the model",
        "mmpilot.open_identification.v1 / open_downstream_property.v1",
        "What animal is present in the evidence?",
        "How many legs does the animal typically have?",
        "no candidate list anywhere in the model-visible prompt",
        "candidates go only to the external teacher-forced scorer",
        "the swap target appears in no visible prompt and no transcript",
        "coordinate exchange (method B)",
        "separate conditions with separate claims",
    ):
        assert statement in svg, statement


def test_the_schematic_does_not_imply_the_open_experiments_have_succeeded():
    svg = SCHEMATIC_SVG.read_text(encoding="utf-8")
    assert "Not yet run. No result exists under any open protocol." in svg
    assert "No result under method B, and no result under any open protocol, exists yet." in svg
    assert "A hidden-intermediate test is a later, stronger stage" in svg
    assert "It is not designed yet." in svg
