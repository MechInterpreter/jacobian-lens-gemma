"""Structure and full MOCK execution of the open-prompt notebook.

The execution test runs every code cell in one namespace with the committed
switch left alone, so it checks two things at once: that the notebook works end
to end on CPU, and that opening it starts nothing. A second run flips the switch
and asserts that the notebook *refuses* — the real open-prompt study does not
exist, and the notebook must not improvise one.

The notebook is generated by ``scripts/_build_open_prompt_notebook.py``; the
structural tests here are what keep the generated file honest.
"""

import ast
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
NOTEBOOK_PATH = REPO_ROOT / "notebooks" / "open_prompt_protocol_mock_colab.ipynb"
BUILDER = REPO_ROOT / "scripts" / "_build_open_prompt_notebook.py"
RUNNER = Path(__file__).resolve().parent / "_open_prompt_notebook_runner.py"

REQUIRED_SECTIONS = [
    "colab bootstrap",
    "the switch, and why it refuses",
    "the legacy candidate-listed mode still functions",
    "the open prompt names no candidate",
    "every refusal, exercised",
    "the transcript is audited and never reaches the model",
    "the candidates are scored externally",
    "order must not move the fingerprint",
    "candidate-completion positions are never patched",
    "the mock effects",
    "summary",
]


@pytest.fixture(scope="module")
def notebook():
    return json.loads(NOTEBOOK_PATH.read_text(encoding="utf-8"))


def _code_cells(payload):
    return [cell for cell in payload["cells"] if cell["cell_type"] == "code"]


def _source(payload):
    return "\n".join("".join(cell["source"]) for cell in payload["cells"])


def _code_source(payload):
    return "\n".join("".join(cell["source"]) for cell in _code_cells(payload))


# ---------------------------------------------------------------- structure


def test_notebook_is_valid_and_output_free(notebook):
    assert notebook["nbformat"] == 4
    for index, cell in enumerate(_code_cells(notebook)):
        assert cell["outputs"] == [], f"code cell {index} has stored outputs"
        assert cell["execution_count"] is None, f"code cell {index} has an exec count"


def test_the_committed_notebook_matches_its_builder():
    result = subprocess.run(
        [sys.executable, str(BUILDER)], capture_output=True, text=True, cwd=REPO_ROOT
    )
    assert result.returncode == 0, result.stderr
    assert subprocess.run(
        ["git", "diff", "--quiet", "--", str(NOTEBOOK_PATH)], cwd=REPO_ROOT
    ).returncode == 0, (
        "the committed notebook differs from what its builder produces; run "
        "python scripts/_build_open_prompt_notebook.py and commit the result"
    )


def test_all_code_cells_parse_and_use_no_shell_magics(notebook):
    for index, cell in enumerate(_code_cells(notebook)):
        source = "".join(cell["source"])
        try:
            ast.parse(source)
        except SyntaxError as exc:  # pragma: no cover - failure path
            pytest.fail(f"code cell {index} does not parse: {exc}")
        for line in source.splitlines():
            assert not line.strip().startswith(("!", "%")), (
                f"code cell {index} uses a shell/line magic: {line!r}"
            )


def test_required_sections_are_present_in_order(notebook):
    text = _source(notebook).lower()
    position = 0
    for heading in REQUIRED_SECTIONS:
        found = text.find(heading, position)
        assert found >= 0, f"missing section {heading!r}"
        position = found


