def test_the_only_switch_is_committed_false_and_refuses(notebook):
    source = _code_source(notebook)
    assert "RUN_REAL_OPEN_PROMPT_STUDY = False" in source
    assert "RUN_REAL_OPEN_PROMPT_STUDY = True" not in source
