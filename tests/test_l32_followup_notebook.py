def test_an_incompatible_resume_is_refused(mock_run, tmp_path):
    """A directory written under one configuration refuses another."""
    from jlens.mmpilot.store import IncompatibleStateError, RunFingerprint, UnitStore

    run_dir = Path(mock_run["run_dir"])
    stored = json.loads((run_dir / "fingerprint.json").read_text(encoding="utf-8"))
    stored.pop("written_utc", None)
    changed = dict(stored)
    changed["selection_config"] = {
        **stored["selection_config"],
        "capability_protocol": "gemma-it-chat-balanced-options-v1",
    }
    with pytest.raises(IncompatibleStateError, match="different configuration"):
        UnitStore(run_dir, RunFingerprint(**changed)).open()


