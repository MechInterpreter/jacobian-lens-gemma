"""Structure and full MOCK execution of the L32 follow-up notebook.

The execution tests run every code cell in one namespace in a clean
interpreter, with the committed switches left alone. That checks two things at
once: the notebook works end to end on CPU, and opening it starts nothing.

A second run flips the paired-reference switches, which is the only
configuration that is meant to change a conclusion (it licenses the cross-layer
comparison).

The notebook is generated by ``scripts/_build_l32_followup_notebook.py``; the
structural tests here are what keep the generated file honest.
"""

