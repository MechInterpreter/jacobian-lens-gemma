def test_the_convergence_controls_all_ran(mock_run):
    from jlens.mmpilot.convergence import CONTROL_VARIANTS

    controls = _report(mock_run)["convergence"]["controls"]
    per_layer = controls["per_layer"]
    cell = per_layer[next(iter(per_layer))]
    for variant in CONTROL_VARIANTS:
        entry = cell["controls"][variant]
        # Each control is scored on the metric it actually perturbs — the label
        # shuffle on target accuracy, the other two on agreement with the
        # model's own answer — so the compared field is named, not assumed.
        assert entry["compared_field"] in (
            "target_accuracy_argmax",
            "clean_agreement_argmax",
        ), (variant, entry["compared_field"])
        assert "control_value" in entry
        assert "chance_rate" in entry
    assert "wrong_layer_control_note" in controls
    assert "all_controls_passed" in controls


