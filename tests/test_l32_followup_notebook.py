def test_retrieval_excludes_the_same_image_not_only_the_same_group(mock_run):
    """The exclusion is by image identity, and it is reported per direction.

    Under the ``image_unique`` profile the subset keeps exactly one synchronized
    group per photograph, so ``n_excluded_same_image_different_group`` is
    necessarily 0 — there is no sibling group left to exclude. That is the
    *stronger* state, not a missing check: the sibling route was closed at
    selection rather than at retrieval. What must hold either way is that the
    image-superseding rule is the one in force, that every query's own group was
    excluded, and that the sibling counter is reported so a future subset that
    does keep siblings is visibly covered.
    """
    from jlens.mmpilot.jspace import EXCLUSION_RULE_VERSION

    assert EXCLUSION_RULE_VERSION == "exclude_same_image_id_supersedes_group.v1"
    report = _report(mock_run)
    provenance = report["split_provenance"]
    assert provenance["n_distinct_images"] == provenance["n_groups"]

    representational = report["representational"]
    layer = next(iter(representational))
    pairs = representational[layer]["pairs"]
    assert len(pairs) == 6, f"expected six directed pairs, got {sorted(pairs)}"
    for name, entry in pairs.items():
        exclusions = entry["exclusions"]
        assert exclusions["rule_version"] == EXCLUSION_RULE_VERSION, name
        assert "n_excluded_same_image_different_group" in exclusions, name
        assert exclusions["n_excluded_same_group"] == exclusions["n_sources"], name
        assert exclusions["n_sources_without_eligible_target"] == 0, name


