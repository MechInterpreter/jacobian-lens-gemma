def test_the_report_phrasing_rule_is_enforced_in_the_notebook(notebook):
    source = _code_source(notebook)
    assert "assert_report_phrasing" in source
    text = _source(notebook).lower()
    assert "before native direct-readout convergence" in text
    # Every occurrence of a forbidden phrase must sit inside a passage that is
    # ruling it out, not asserting it. Checked over a window rather than a line,
    # because the prose wraps.
    for phrase in ("pre-linguistic", "language-free", "before language exists"):
        start = 0
        while (index := text.find(phrase, start)) != -1:
            window = text[max(0, index - 400) : index + 400]
            assert "never" in window, f"{phrase!r} used as a claim near: {window}"
            start = index + len(phrase)


