"""Structure and full MOCK execution of the L32 convergence-resolution notebook.

The execution tests run every code cell in one namespace in a clean interpreter,
with the committed switches left alone. That checks two things at once: the
notebook works end to end on CPU, and opening it starts nothing.

Three further runs flip exactly one thing each — the Stage-B override, an
interrupted session, and a resumed one — because those are the paths whose
failure modes are silent.

The notebook is generated by ``scripts/_build_l32_resolution_notebook.py``; the
structural tests here are what keep the generated file honest.
"""

