def test_an_interrupted_run_resumes_and_reuses_its_units(tmp_path_factory):
    """A half-finished run directory is picked up, not restarted.

    The first pass is cut off after the convergence-scoring cell, which is the
    only cell that writes readout units; the second pass runs the whole
    notebook against the same run directory and must report the units as
    *reused* rather than recomputed.
    """
    workspace = tmp_path_factory.mktemp("resume")
    scratch = workspace / "s"
    run_dir = workspace / "mml32res_mock_resume_test"
    environment_run_dir = str(run_dir)

    def _go(stop_after=None):
        environment = dict(os.environ)
        environment.pop("PYTHONPATH", None)
        environment["MMPILOT_REPO_DIR"] = str(REPO_ROOT)
        environment["MMPILOT_SCRATCH"] = str(scratch)
        environment["MMPILOT_RUN_DIR"] = environment_run_dir
        arguments = [str(RUNNER), str(NOTEBOOK_PATH)]
        if stop_after is not None:
            arguments += ["--stop-after", str(stop_after)]
        result = subprocess.run(
            [sys.executable, *arguments],
            capture_output=True,
            text=True,
            cwd=str(workspace),
            env=environment,
        )
        return json.loads(result.stdout.strip().splitlines()[-1])

    # Cell 26 is 13b, the convergence-scoring cell. Anything at or past it
    # leaves a partially populated run directory behind.
    interrupted = _go(stop_after=26)
    assert interrupted.get("ok"), interrupted
    assert (run_dir / "convergence" / "readout_units").is_dir()
    n_units = len(list((run_dir / "convergence" / "readout_units").glob("*.json")))
    assert n_units > 0

    resumed = _ok(_go())
    assert resumed["RESUME.run_state"] == "resuming"
    assert resumed["RESUME.units_reused"] == n_units
    assert resumed["RESUME.units_computed"] == 0


def test_a_changed_scientific_configuration_refuses_the_resume(tmp_path_factory):
    """Reusing a run directory under a different population is a refusal."""
    from jlens.mmpilot.convergence import ConvergenceFingerprint, ConvergenceStore
    from jlens.mmpilot.store import IncompatibleStateError

    root = tmp_path_factory.mktemp("fp") / "conv"
    common = dict(
        protocol="mmpilot.output_convergence_audit.v1",
        completed_run_fingerprint_digest="sha256:a",
        completed_run_dir=str(root),
        model_repo_id="mock/gemma-like",
        model_revision="mock",
        processor_revision="mock",
        layers=(1,),
        candidate_digest="sha256:candidates",
        readout_mode="single_token_complete",
        head_checksum="sha256:head",
        criterion_digest="sha256:criterion",
        code_version="mmpilot.l32_convergence_resolution.v1",
    )
    ConvergenceStore(
        root, ConvergenceFingerprint(**common, extra={"population_digest": "A"})
    ).open()
    with pytest.raises(IncompatibleStateError):
        ConvergenceStore(
            root, ConvergenceFingerprint(**common, extra={"population_digest": "B"})
        ).open()
