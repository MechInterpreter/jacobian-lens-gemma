def _run(tmp_path, *overrides, stop_after=None, scratch=None):
    environment = dict(os.environ)
    environment.pop("PYTHONPATH", None)
    environment["MMPILOT_REPO_DIR"] = str(REPO_ROOT)
    environment["MMPILOT_SCRATCH"] = str(scratch or (tmp_path / "s"))
    arguments = [str(RUNNER), str(NOTEBOOK_PATH), *overrides]
    if stop_after is not None:
        arguments += ["--stop-after", str(stop_after)]
    result = subprocess.run(
        [sys.executable, *arguments],
        capture_output=True,
        text=True,
        cwd=str(tmp_path),
        env=environment,
    )
    payload = json.loads(result.stdout.strip().splitlines()[-1])
    return payload


def _ok(payload):
    assert payload.get("ok"), payload
    return payload


